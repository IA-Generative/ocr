// `unplugin-auto-import` regenerates this file on every dev/build run and it is
// gitignored, so a fresh clone lints before it ever exists. Read it defensively
// rather than crashing the whole config.
function autoImportGlobals () {
  try {
    const url = new URL('./.eslintrc-auto-import.json', import.meta.url)
    return JSON.parse(readFileSync(url, 'utf-8')).globals ?? {}
  } catch {
    return {}
  }
}

